/// Render the native print preview for a generated document.
Future<void> _printDocument(pw.Document doc, String name) async {
  await Printing.layoutPdf(
    name: name,
    onLayout: (format) async => doc.save(),
  );
}

/// Print a submitted Enterprise Visit Plan (any status — shows objectives,
/// expected outcomes, resources, approval status and sign-off block).
Future<void> printVisitPlanPdf(Map<String, dynamic> data) async {
  final doc = pw.Document(title: 'Enterprise Visit Plan');
  doc.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(32),
      header: (context) => _header('Enterprise Visit Plan'),
      footer: _footer,
      build: (context) => [
        _detailsTable([
          ['Document Type', 'Enterprise Visit Plan'],
          ['Date', _fmtDate(data['timestamp'])],
          ['Department', _orDash(data['department'])],
          ['Expert Name', _orDash(data['expertName'] ?? data['submittedBy'])],
          ['Enterprise Name', _orDash(data['targetEnterprise'])],
          ['Location / Woreda', _orDash(data['location'])],
          [
            'Visit Dates',
            '${_orDash(data['startDate'])}  →  ${_orDash(data['endDate'])}',
          ],
          ['Expert Contact', _orDash(data['submittedBy'])],
        ]),
        _sectionTitle('Objectives & Planned Tasks'),
        ..._bullets(_lines(data['tasks'] ?? data['description']?.toString())),
        if (_str(data['expectedOutcomes']).isNotEmpty) ...[
          _sectionTitle('Expected Outcomes'),
          pw.Text(_str(data['expectedOutcomes']), style: const pw.TextStyle(fontSize: 9, height: 1.4)),
        ],
        if (_str(data['resources']).isNotEmpty) ...[
          _sectionTitle('Resources / Tools Required'),
          pw.Text(_str(data['resources']), style: const pw.TextStyle(fontSize: 9, height: 1.4)),
        ],
        _sectionTitle('Approval Status'),
        _statusBlock(data),
        pw.SizedBox(height: 14),
        _signOffBlock(),
      ],
    ),
  );
  await _printDocument(doc, 'GIC_Visit_Plan');
}

/// Print a completed Enterprise Visit Support Report — renders the chosen
/// report template's dynamic sections (or legacy fields), findings,
/// recommendations, approval status and sign-off block.
Future<void> printSupportReportPdf(Map<String, dynamic> data) async {
  final doc = pw.Document(title: 'Enterprise Visit Support Report');
  final templateSections = _templateSections(data);
  doc.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(32),
      header: (context) => _header('Enterprise Visit Support Report'),
      footer: _footer,
      build: (context) => [
        _detailsTable([
          ['Document Type', 'Enterprise Visit Support Report'],
          [
            'Report Date',
            _fmtDate(data['reportDate'] ?? data['completedAt'] ?? data['timestamp']),
          ],
          ['Department', _orDash(data['department'])],
          ['Expert Name', _orDash(data['expertName'] ?? data['submittedBy'])],
          ['Enterprise Name', _orDash(data['targetEnterprise'])],
          ['Location / Woreda', _orDash(data['location'])],
          ['Sector', _orDash(data['sector'])],
          if (_str(data['reportTemplate']).isNotEmpty)
            ['Report Format', _str(data['reportTemplate'])],
          ['Verified By', _orDash(data['verifiedBy'])],
        ]),
        if (templateSections.isNotEmpty)
          ...templateSections
        else
          ..._legacySections(data),
        if (_str(data['expectedOutcomes']).isNotEmpty) ...[
          _sectionTitle('Expected Outcomes'),
          pw.Text(_str(data['expectedOutcomes']), style: const pw.TextStyle(fontSize: 9, height: 1.4)),
        ],
        _sectionTitle('Approval Status'),
        _statusBlock(data),
        pw.SizedBox(height: 14),
        _signOffBlock(),
      ],
    ),
  );
  await _printDocument(doc, 'GIC_Visit_Report');
}

/// Print Enterprise contact details from the department enterprise directory.
Future<void> printEnterpriseDetailsPdf(Map<String, dynamic> data) async {
  final doc = pw.Document(title: 'Enterprise Details');
  final bool isModel = data['isModel'] == true;
  doc.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(32),
      header: (context) => _header('Enterprise Contact Details'),
      footer: _footer,
      build: (context) => [
        _detailsTable([
          ['Enterprise Name', _orDash(data['entName'])],
          ['Industry Sector', _orDash(data['sector'])],
          ['Type', isModel ? 'Model Enterprise' : 'Standard Enterprise'],
          ['Department', _orDash(data['department'])],
          ['Location / Address', _orDash(data['address'] ?? data['woreda'])],
          ['Contact Person', _orDash(data['contactPerson'] ?? data['repName'])],
          ['Position / Role', _orDash(data['position'])],
          ['Phone', _orDash(data['phone'])],
          ['Email', _orDash(data['email'])],
        ]),
        pw.SizedBox(height: 20),
        _signOffBlock(),
      ],
    ),
  );
  await _printDocument(doc, 'GIC_Enterprise_Details');
}
